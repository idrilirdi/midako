#!/usr/bin/env python3
"""Convert drashna's 128x32 OLED bongocat frames into LVGL 8 alpha-1bit images.

The OLED frames use the SSD1306 page layout (each byte is 8 vertical pixels,
128 bytes per page, 4 pages). This script decodes them, crops every frame to
the shared bounding box, scales them by an integer factor and writes LVGL
`lv_img_dsc_t` descriptors in LV_IMG_CF_ALPHA_1BIT format. The image color is
taken from the `img_recolor` style, so it follows the active theme.

Usage:
    python3 tools/bongocat_to_lvgl.py ../../drashna/bongocats/bongocat_assets.c screens/bongocat_img.c [scale]
"""

import re
import sys

W, H = 128, 32


def parse_frames(path):
    src = open(path).read()
    src = re.sub(r"//[^\n]*", "", src)
    frames = {}
    for m in re.finditer(r"bongocats_(\w+)\[[^\]]*\]\[[^\]]*\]\s*=\s*\{(.*?)\};", src, re.S):
        frames[m.group(1)] = [
            [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", body)] for body in re.findall(r"\{([^{}]*)\}", m.group(2))
        ]
    return frames


def pixel(frame, x, y):
    return (frame[(y // 8) * W + x] >> (y % 8)) & 1


def main():
    src, dst = sys.argv[1], sys.argv[2]
    scale = int(sys.argv[3]) if len(sys.argv) > 3 else 2
    frames = parse_frames(src)
    order = [("idle", frames["idle"]), ("prep", frames["prep"]), ("tap", frames["tap"])]

    xs, ys = [], []
    for _, group in order:
        for f in group:
            for y in range(H):
                for x in range(W):
                    if pixel(f, x, y):
                        xs.append(x)
                        ys.append(y)
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    cw, ch = x1 - x0 + 1, y1 - y0 + 1
    ow, oh = cw * scale, ch * scale
    stride = (ow + 7) // 8

    out = [
        "// Generated by tools/bongocat_to_lvgl.py from drashna/bongocats/bongocat_assets.c. Do not edit.",
        "// Original art: Copyright 2022 HorrorTroll, 2025 drashna. SPDX-License-Identifier: GPL-2.0-or-later",
        '#include "lvgl.h"',
        '#include "bongocat_img.h"',
        "",
    ]
    names = {}
    for group_name, group in order:
        names[group_name] = []
        for i, f in enumerate(group):
            name = f"bongocat_{group_name}_{i}"
            names[group_name].append(name)
            data = bytearray()
            for oy in range(oh):
                row = bytearray(stride)
                for ox in range(ow):
                    if pixel(f, x0 + ox // scale, y0 + oy // scale):
                        row[ox // 8] |= 0x80 >> (ox % 8)
                data += row
            out.append(f"static const uint8_t {name}_map[] = {{")
            for k in range(0, len(data), 16):
                out.append("    " + ", ".join(f"0x{b:02x}" for b in data[k : k + 16]) + ",")
            out.append("};")
            out.append(f"static const lv_img_dsc_t {name} = {{")
            out.append("    .header.cf          = LV_IMG_CF_ALPHA_1BIT,")
            out.append("    .header.always_zero = 0,")
            out.append(f"    .header.w           = {ow},")
            out.append(f"    .header.h           = {oh},")
            out.append(f"    .data_size          = sizeof({name}_map),")
            out.append(f"    .data               = {name}_map,")
            out.append("};")
            out.append("")
    for group_name, _ in order:
        out.append(f"const lv_img_dsc_t *const bongocat_{group_name}[] = {{{', '.join('&' + n for n in names[group_name])}}};")
    open(dst, "w").write("\n".join(out) + "\n")

    hdr = dst.rsplit(".", 1)[0] + ".h"
    open(hdr, "w").write(
        "\n".join(
            [
                "// Generated by tools/bongocat_to_lvgl.py. Do not edit.",
                "#pragma once",
                "",
                '#include "lvgl.h"',
                "",
                f"#define BONGOCAT_IMG_WIDTH {ow}",
                f"#define BONGOCAT_IMG_HEIGHT {oh}",
                f"#define BONGOCAT_IDLE_FRAMES {len(frames['idle'])}",
                f"#define BONGOCAT_PREP_FRAMES {len(frames['prep'])}",
                f"#define BONGOCAT_TAP_FRAMES {len(frames['tap'])}",
                "",
                "extern const lv_img_dsc_t *const bongocat_idle[BONGOCAT_IDLE_FRAMES];",
                "extern const lv_img_dsc_t *const bongocat_prep[BONGOCAT_PREP_FRAMES];",
                "extern const lv_img_dsc_t *const bongocat_tap[BONGOCAT_TAP_FRAMES];",
                "",
            ]
        )
    )
    print(f"crop x={x0}..{x1} y={y0}..{y1} -> {ow}x{oh}, {len(frames['idle'])}+{len(frames['prep'])}+{len(frames['tap'])} frames")


if __name__ == "__main__":
    main()
